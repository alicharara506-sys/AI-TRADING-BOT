"""Runs the full benchmark suite and prints a report.

    python3 -m benchmarks.run_all

The numbers in docs/benchmarks/results.md were generated by piping this
script's output; re-run it and update that file after any change to the
Event Bus, backtest engine, or Signal Fusion hot paths.
"""

from __future__ import annotations

import asyncio
import platform
from datetime import UTC, datetime

from benchmarks import backtest_engine_benchmark, event_bus_benchmark, signal_fusion_benchmark


async def main() -> None:
    print(f"# Benchmark run: {datetime.now(UTC).isoformat()}")
    print(f"Python {platform.python_version()} on {platform.platform()}")
    print()

    print("## Event Bus")
    for result in await event_bus_benchmark.run():
        print(
            f"- {result.label}: {result.events_per_second:,.0f} deliveries/sec "
            f"({result.event_count:,} events in {result.elapsed_seconds * 1000:.1f} ms)"
        )
    print()

    print("## Backtest execution engine")
    backtest_result = await backtest_engine_benchmark.run()
    print(
        f"- {backtest_result.bars_per_second:,.0f} bars/sec "
        f"({backtest_result.bar_count:,} bars, {backtest_result.order_count} orders, "
        f"{backtest_result.elapsed_seconds * 1000:.1f} ms total)"
    )
    print()

    print("## Signal Fusion (full quant module roster)")
    signal_result = signal_fusion_benchmark.run()
    print(
        f"- {signal_result.evaluations_per_second:,.0f} evaluations/sec "
        f"(window={signal_result.window_size}, mean={signal_result.mean_latency_ms:.3f} ms, "
        f"median={signal_result.median_latency_ms:.3f} ms, "
        f"p95={signal_result.p95_latency_ms:.3f} ms, "
        f"{signal_result.evaluation_count:,} evaluations in {signal_result.elapsed_seconds:.2f}s)"
    )


if __name__ == "__main__":
    asyncio.run(main())
